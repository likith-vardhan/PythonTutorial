# strings
name = "Alice"
greeting = 'Hello, World!'
sentence = "I love Python"

print(type(name))   # Output: <class 'str'>

# integer-int
age = 25
temperature = -10
score = 0

print(type(age))    # Output: <class 'int'>

# float

price = 99.99
height = 5.8
pi = 3.14159

print(type(pi))     # Output: <class 'float'>


# Boolean

is_raining = True
is_logged_in = False
has_passed = True

print(type(is_raining))   # Output: <class 'bool'>

