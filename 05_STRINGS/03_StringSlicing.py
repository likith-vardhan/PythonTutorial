name = "Bengaluru"
#       0 1 2 3 4 5 6 7 8

print(name[0:4])    # Beng   — index 0,1,2,3 (4 not included)
print(name[4:])     # aluru  — from index 4 to end
print(name[:5])     # Benga  — from start to index 4
print(name[::2])    # Bnlr   — every 2nd character
print(name[::-1])   # urulagneB — reversed! (step of -1)

