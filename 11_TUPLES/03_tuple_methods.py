# Tuple Methods
# Tuples have only 2 methods (because they're immutable):
pythonnums = (3, 1, 4, 1, 5, 9, 1)

print(nums.count(1))   # 3 — how many times 1 appears
print(nums.index(5))   # 4 — index of first occurrence of 5
print(len(nums))       # 7
print(sum(nums))       # 24
print(min(nums))       # 1
print(max(nums))       # 9
