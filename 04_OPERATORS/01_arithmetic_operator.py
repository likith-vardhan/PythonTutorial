a = 20
b = 6

print(a + b)   # Addition       → 26
print(a - b)   # Subtraction    → 14
print(a * b)   # Multiplication → 120
print(a / b)   # Division       → 3.3333... (always float)
print(a // b)  # Floor Division → 3 (drops the decimal)
print(a % b)   # Modulus        → 2 (remainder after division)
print(a ** b)  # Exponent       → 64000000 (20 to the power 6)

# Is a number even or odd?
print(10 % 2)   # 0 → Even (no remainder)
print(7 % 2)    # 1 → Odd (remainder of 1)